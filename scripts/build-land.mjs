/**
 * Generates src/data/worldLand.js — real world coastlines (Natural Earth 110m)
 * projected later at runtime with d3-geo (orthographic).
 *
 * Run: node scripts/build-land.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { feature } from 'topojson-client';

const SRC = path.resolve('node_modules/world-atlas/land-110m.json');
const OUT = path.resolve('src/data/worldLand.js');

const topo = JSON.parse(fs.readFileSync(SRC, 'utf8'));
const land = feature(topo, topo.objects.land);
const landGeometry = land.type === 'FeatureCollection' ? land.features[0].geometry : land.geometry;

// Natural Earth land is a MultiPolygon of [rings]; keep outer rings only and
// round coordinates to 0.1° (≈11 km) which is far beyond the logo's needs.
const round = (n) => Math.round(n * 5) / 5; // 0.2° ≈ 22 km

/* Douglas–Peucker simplification keeps coastlines recognisable at logo sizes. */
const sqDistToSegment = (p, a, b) => {
  let [x, y] = a;
  let dx = b[0] - x;
  let dy = b[1] - y;
  if (dx !== 0 || dy !== 0) {
    const t = ((p[0] - x) * dx + (p[1] - y) * dy) / (dx * dx + dy * dy);
    if (t > 1) {
      x = b[0];
      y = b[1];
    } else if (t > 0) {
      x += dx * t;
      y += dy * t;
    }
  }
  dx = p[0] - x;
  dy = p[1] - y;
  return dx * dx + dy * dy;
};

const simplify = (points, tolerance) => {
  const sq = tolerance * tolerance;
  const run = (first, last) => {
    let maxSq = sq;
    let index = -1;
    for (let i = first + 1; i < last; i += 1) {
      const d = sqDistToSegment(points[i], points[first], points[last]);
      if (d > maxSq) {
        index = i;
        maxSq = d;
      }
    }
    if (index === -1) return;
    if (index - first > 1) run(first, index);
    points[index].keep = true;
    if (last - index > 1) run(index, last);
  };
  const pts = points.map((p) => ({ p, keep: false }));
  pts[0].keep = true;
  pts[pts.length - 1].keep = true;
  if (pts.length > 2) {
    const flat = pts.map((o) => o.p);
    const runFlat = (first, last) => {
      let maxSq = sq;
      let index = -1;
      for (let i = first + 1; i < last; i += 1) {
        const d = sqDistToSegment(flat[i], flat[first], flat[last]);
        if (d > maxSq) {
          index = i;
          maxSq = d;
        }
      }
      if (index === -1) return;
      pts[index].keep = true;
      if (index - first > 1) runFlat(first, index);
      if (last - index > 1) runFlat(index, last);
    };
    runFlat(0, pts.length - 1);
  }
  void run;
  return pts.filter((o) => o.keep).map((o) => o.p);
};

const cleanRing = (ring) => {
  const out = [];
  for (const [lon, lat] of ring) {
    const p = [round(lon), round(lat)];
    const prev = out[out.length - 1];
    if (!prev || prev[0] !== p[0] || prev[1] !== p[1]) out.push(p);
  }
  const thin = simplify(out, 0.55);
  return thin.length >= 4 ? thin : null;
};

const polygons = [];
for (const polygon of landGeometry.coordinates) {
  const ring = cleanRing(polygon[0]);
  if (!ring) continue;
  // discard specks invisible at logo sizes (rough area test)
  let area = 0;
  for (let i = 0; i < ring.length - 1; i += 1) {
    area += ring[i][0] * ring[i + 1][1] - ring[i + 1][0] * ring[i][1];
  }
  if (Math.abs(area / 2) < 14) continue;
  polygons.push([ring]);
}

const geojson = { type: 'Feature', properties: {}, geometry: { type: 'MultiPolygon', coordinates: polygons } };

const file = `/**
 * Natural Earth 110m land polygons (public domain), rounded for the globe mark.
 * Generated by scripts/build-land.mjs — do not edit by hand.
 */
export const WORLD_LAND = ${JSON.stringify(geojson)};

export default WORLD_LAND;
`;

fs.writeFileSync(OUT, file);
console.log(`wrote ${OUT} — ${polygons.length} land masses, ${(file.length / 1024).toFixed(1)} kB`);
